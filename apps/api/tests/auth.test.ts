import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, randomBytes, createHash } from 'node:crypto';
import { decodeJwt, SignJWT } from 'jose';
import { hash } from 'argon2';
import { eq, inArray } from 'drizzle-orm';
import { buildApp } from '../src/app.js';
import { connectDatabase } from '../src/db.js';
import { groups, users, sessions } from '../src/schema.js';

test('authentication against PostgreSQL: isolation, CSRF, rotation, expiration and logout', async () => {
 const c=connectDatabase(); const app=buildApp({logger:false,origin:'http://localhost:5173',secureCookies:false});
 const groupId=randomUUID(); const ids=[randomUUID(),randomUUID()]; const suffix=randomUUID();
 const password=randomBytes(24).toString('hex'); const passwordHash=await hash(password);
 const headers={'x-csrf-protection':'1',origin:'http://localhost:5173'};
 const login=(n:number, cookie?:string) => app.inject({method:'POST',url:'/api/auth/login',headers:{...headers,...(cookie?{cookie}:{})},payload:{email:`test-${suffix}-${n}@edu.mukpid.ru`,password}});
 const getCookie=(r:{headers:Record<string,unknown>})=>String(r.headers['set-cookie']).split(';')[0];
 const me=(cookie?:string,url='/api/auth/me')=>app.inject({method:'GET',url,headers:cookie?{cookie}:{}});
 try {
  await c.db.insert(groups).values({id:groupId,name:`TEST-${suffix}`,faculty:'Тестовый',program:'Тестовая',year:1});
  await c.db.insert(users).values(ids.map((id,i)=>({id,email:`test-${suffix}-${i}@edu.mukpid.ru`,fullName:`Вымышленный студент ${i}`,faculty:'Тестовый',role:'student',groupId,passwordHash})));
  assert.equal((await me()).statusCode,401);
  assert.equal((await me('session=forged')).statusCode,401);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/login',payload:{email:`test-${suffix}-0@edu.mukpid.ru`,password}})).statusCode,403);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/login',headers:{...headers,origin:'https://evil.example'},payload:{email:`test-${suffix}-0@edu.mukpid.ru`,password}})).statusCode,403);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:'x'}})).statusCode,400);
  const bad=await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:`test-${suffix}-0@edu.mukpid.ru`,password:'wrong'}});
  const missing=await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:'missing-'+suffix+'@example.test',password:'wrong'}});
  assert.equal(bad.statusCode,401); assert.equal(bad.body,missing.body);
  const a=await login(0); const b=await login(1); assert.equal(a.statusCode,200); assert.equal(b.statusCode,200);
  assert.match(String(a.headers['set-cookie']),/HttpOnly/); assert.match(String(a.headers['set-cookie']),/SameSite=Lax/);
  const ac=getCookie(a),bc=getCookie(b);
  const profile=(await me(ac)).json().data; assert.equal(profile.id,ids[0]);
  assert.deepEqual(Object.keys(profile).sort(),['id','fullName','email','role','faculty','department','program','year','groupName'].sort());
  assert.equal((await me(bc)).json().data.id,ids[1]);
  assert.equal((await me(ac,`/api/auth/me?studentId=${ids[1]}`)).json().data.id,ids[0]);
  const rotated=await login(0,ac); assert.equal(rotated.statusCode,200); assert.equal((await me(ac)).statusCode,401);
  const rc=getCookie(rotated); const token=rc.slice(rc.indexOf('=')+1);
  const [session]=await c.db.select().from(sessions).where(eq(sessions.userId,ids[0]));
  assert.equal(session.tokenHash,createHash('sha256').update(decodeJwt(token).jti!).digest('hex')); assert.notEqual(session.tokenHash,token);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/logout',headers:{cookie:rc}})).statusCode,403);
  assert.equal((await me(rc)).statusCode,200);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/logout',headers:{...headers,cookie:rc}})).statusCode,204);
  assert.equal((await me(rc)).statusCode,401); assert.equal((await me(bc)).statusCode,200);
  await c.db.update(sessions).set({expiresAt:new Date(Date.now()-1000)}).where(eq(sessions.userId,ids[1]));
  assert.equal((await me(bc)).statusCode,401);
  const teacherId=randomUUID(); ids.push(teacherId);
  await c.db.insert(users).values({id:teacherId,email:`teacher-${suffix}@mukpid.ru`,fullName:'Вымышленный преподаватель',faculty:'Тестовый',role:'teacher',passwordHash});
  const tr=await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:`teacher-${suffix}@mukpid.ru`,password}});
  assert.equal(tr.statusCode,200); const tc=getCookie(tr);
  assert.equal((await me(tc)).json().data.role,'teacher'); assert.equal((await me(tc)).json().data.groupName,null);
  assert.equal((await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:`TEACHER-${suffix}@MUKPID.RU`,password}})).statusCode,200);
  const staffId=randomUUID(); ids.push(staffId);
  await c.db.insert(users).values({id:staffId,email:`staff-${suffix}@staff.mukpid.ru`,fullName:'Вымышленный сотрудник',faculty:'Тестовый',role:'staff',passwordHash});
  const sr=await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:`staff-${suffix}@staff.mukpid.ru`,password}});
  assert.equal(sr.statusCode,200);
  assert.equal((await me(getCookie(sr))).json().data.role,'staff');
  await c.db.update(users).set({faculty:'Обновлённый'}).where(eq(users.id,teacherId));
  assert.equal((await me(tc)).json().data.faculty,'Обновлённый');
  const forged=await new SignJWT({}).setProtectedHeader({alg:'HS256'}).setSubject(teacherId).setJti(randomBytes(32).toString('base64url')).setIssuer('mukpid-api').setAudience('mukpid-web').setIssuedAt().setExpirationTime('8h').sign(randomBytes(32));
  assert.equal((await me('session='+forged)).statusCode,401);
  const expired=await new SignJWT({}).setProtectedHeader({alg:'HS256'}).setSubject(teacherId).setJti(decodeJwt(tc.slice(tc.indexOf('=')+1)).jti!).setIssuer('mukpid-api').setAudience('mukpid-web').setIssuedAt().setExpirationTime('1 second ago').sign(new TextEncoder().encode(process.env.JWT_SECRET));
  assert.equal((await me('session='+expired)).statusCode,401);
  let limited=false;
  for(let i=0;i<11;i++){ const r=await app.inject({method:'POST',url:'/api/auth/login',headers,payload:{email:'missing-'+suffix+'@example.test',password:'wrong'}}); if(r.statusCode===429){limited=true;break;} }
  assert(limited);
 } finally {
  await app.close();
  await c.db.delete(users).where(inArray(users.id,ids));
  await c.db.delete(groups).where(eq(groups.id,groupId));
  await c.close();
 }
});
