import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { hash } from 'argon2';
import { eq, inArray } from 'drizzle-orm';
import { buildApp } from '../src/app.js';
import { connectDatabase } from '../src/db.js';
import { groups, users, requests, notifications, sessions } from '../src/schema.js';

test('requests: persistence, validation, ownership, roles, cancellation and revoked sessions', async () => {
  const c = connectDatabase();
  const app = buildApp({ logger: false, secureCookies: false, origin: 'http://localhost:5173' });
  const groupId = randomUUID(), suffix = randomUUID();
  const ids = [randomUUID(), randomUUID(), randomUUID(), randomUUID()];
  const password = randomBytes(24).toString('hex'), passwordHash = await hash(password);
  const csrf = { 'x-csrf-protection': '1', origin: 'http://localhost:5173' };
  const input = { type: 'study', purpose: '  Для тестового учреждения  ', comment: 'Тест', delivery: 'pdf' };
  try {
    await c.db.insert(groups).values({ id: groupId, name: `REQUEST-${suffix}`, faculty: 'Тест', program: 'Тест', year: 1 });
    await c.db.insert(users).values(ids.map((id, i) => ({ id, email: `request-${suffix}-${i}@example.test`, fullName: 'Вымышленный пользователь', faculty: 'Тест', role: i === 3 ? 'staff' : i === 2 ? 'teacher' : 'student', groupId: i >= 2 ? null : groupId, passwordHash })));
    const cookies: string[] = [];
    for (let i = 0; i < 4; i++) {
      const res = await app.inject({ method: 'POST', url: '/api/auth/login', headers: csrf, payload: { email: `request-${suffix}-${i}@example.test`, password } });
      assert.equal(res.statusCode, 200);
      cookies.push(String(res.headers['set-cookie']).split(';')[0]!);
    }
    const list = (i: number) => app.inject({ method: 'GET', url: '/api/requests', headers: { cookie: cookies[i]! } });
    const create = (payload: object, i = 0) => app.inject({ method: 'POST', url: '/api/requests', headers: { ...csrf, cookie: cookies[i]! }, payload });
    const cancel = (id: string, i = 0) => app.inject({ method: 'PATCH', url: `/api/requests/${id}/cancel`, headers: { ...csrf, cookie: cookies[i]! } });
    assert.equal((await app.inject({ method: 'GET', url: '/api/requests' })).statusCode, 401);
    assert.equal((await app.inject({ method: 'GET', url: '/api/requests', headers: { cookie: 'session=forged' } })).statusCode, 401);
    assert.equal((await list(2)).statusCode, 403);
    assert.equal((await create(input, 2)).statusCode, 403);
    assert.equal((await create({ ...input, purpose: '  ' })).statusCode, 400);
    assert.equal((await create({ ...input, type: 'unknown' })).statusCode, 400);
    assert.equal((await create({ ...input, delivery: 'unknown' })).statusCode, 400);
    assert.equal((await create({ ...input, purpose: 'x'.repeat(501) })).statusCode, 400);
    assert.equal((await create({ ...input, comment: 'x'.repeat(2001) })).statusCode, 400);
    assert.equal((await app.inject({ method: 'POST', url: '/api/requests', headers: { cookie: cookies[0]! }, payload: input })).statusCode, 403);
    const created = await create({ ...input, studentId: ids[1] });
    assert.equal(created.statusCode, 201);
    const row = created.json().data;
    assert.equal(row.studentId, ids[0]); assert.equal(row.purpose, input.purpose.trim()); assert.equal(row.status, 'submitted');
    assert.equal((await list(0)).json().data[0].id, row.id);
    assert.deepEqual((await list(1)).json().data, []);
    const second = await create({ ...input, delivery: 'office' }, 1);
    assert.equal(second.statusCode, 201);
    assert.equal((await list(1)).json().data[0].id, second.json().data.id);
    assert.equal((await list(0)).json().data.length, 1);
    assert.equal((await c.db.select().from(notifications).where(eq(notifications.studentId, ids[0]!))).length, 1);
    assert.equal((await cancel(row.id, 1)).statusCode, 403);
    assert.equal((await cancel(row.id, 2)).statusCode, 403);
    assert.equal((await cancel(randomUUID())).statusCode, 404);
    assert.equal((await cancel('invalid')).statusCode, 400);
    assert.equal((await cancel(row.id)).json().data.status, 'cancelled');
    assert.equal((await cancel(row.id)).statusCode, 200);
    assert.equal((await list(0)).json().data[0].status, 'cancelled');
    const ready = (await create(input)).json().data;
    await c.db.update(requests).set({ status: 'ready' }).where(eq(requests.id, ready.id));
    assert.equal((await cancel(ready.id)).statusCode, 409);
    const processRow = (await create(input)).json().data;
    const status = (value: string, i = 3, id = processRow.id) => app.inject({ method: 'PATCH', url: `/api/staff/requests/${id}/status`, headers: { ...csrf, cookie: cookies[i]! }, payload: { status: value } });
    const pdf = (i: number, id = processRow.id, staff = false) => app.inject({ method: 'GET', url: `/api/${staff ? 'staff/' : ''}requests/${id}/pdf`, headers: { cookie: cookies[i]! } });
    assert.equal((await status('ready', 0)).statusCode, 403);
    assert.equal((await status('ready', 2)).statusCode, 403);
    assert.equal((await app.inject({ method: 'GET', url: '/api/staff/requests', headers: { cookie: cookies[0]! } })).statusCode, 403);
    assert.equal((await pdf(0)).statusCode, 409);
    assert.equal((await status('in_progress')).statusCode, 200);
    assert.equal((await status('ready')).statusCode, 200);
    assert.equal((await status('in_progress')).statusCode, 409);
    assert.equal((await status('ready', 3, row.id)).statusCode, 409);
    assert.equal((await pdf(1)).statusCode, 403);
    assert.equal((await pdf(2)).statusCode, 403);
    const document = await pdf(0);
    assert.equal(document.statusCode, 200);
    assert.match(document.headers['content-type']!, /application\/pdf/);
    assert.equal(document.rawPayload.subarray(0, 5).toString(), '%PDF-');
    assert.equal((await pdf(3, processRow.id, true)).statusCode, 200);
    assert.equal((await status('ready')).statusCode, 200);
    assert.deepEqual((await pdf(0)).rawPayload, document.rawPayload);
    assert.equal((await status('issued')).statusCode, 200);
    assert.deepEqual((await pdf(0)).rawPayload, document.rawPayload);
    assert.equal((await status('ready')).statusCode, 409);
    assert.equal((await cancel(processRow.id)).statusCode, 409);
    assert.equal('documentBase64' in (await list(0)).json().data[0], false);
    const office = second.json().data;
    assert.equal((await status('ready', 3, office.id)).statusCode, 200);
    assert.equal((await pdf(1, office.id)).statusCode, 409);
    assert.equal((await pdf(3, office.id, true)).statusCode, 200);
    const staffList = await app.inject({ method: 'GET', url: '/api/staff/requests', headers: { cookie: cookies[3]! } });
    assert.equal(staffList.statusCode, 200);
    assert(staffList.json().data.some((r: { id: string }) => r.id === row.id));
    assert.equal('documentBase64' in staffList.json().data[0], false);
    await c.db.delete(sessions).where(eq(sessions.userId, ids[0]!));
    assert.equal((await list(0)).statusCode, 401);
    assert.equal((await pdf(0)).statusCode, 401);
    assert.equal((await create(input)).statusCode, 401);
    assert.equal((await cancel(ready.id)).statusCode, 401);
  } finally {
    await app.close();
    await c.db.delete(notifications).where(inArray(notifications.studentId, ids));
    await c.db.delete(requests).where(inArray(requests.studentId, ids));
    await c.db.delete(users).where(inArray(users.id, ids));
    await c.db.delete(groups).where(eq(groups.id, groupId));
    await c.close();
  }
});
