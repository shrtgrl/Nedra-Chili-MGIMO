import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { hash } from 'argon2';
import { eq, inArray } from 'drizzle-orm';
import { buildApp } from '../src/app.js';
import { connectDatabase } from '../src/db.js';
import { gradeEntries, groups, inquiries, inquiryReplies, lessons, materials, notifications, requests, sessions, subjects, teachingAssignments, users } from '../src/schema.js';
test('end-to-end API: two students, two teachers, object isolation, atomic grades, files, replies and schedule races', async () => {
    const c = connectDatabase(), app = buildApp({ logger: false, origin: 'http://localhost:5173', secureCookies: false });
    const suffix = randomUUID(), studentA = randomUUID(), studentB = randomUUID(), teacherA = randomUUID(), teacherB = randomUUID(), staff = randomUUID();
    const ids = [studentA, studentB, teacherA, teacherB, staff], groupIds = [randomUUID(), randomUUID()], subjectId = randomUUID(), assignmentIds = [randomUUID(), randomUUID()];
    const password = randomBytes(24).toString('hex'), passwordHash = await hash(password), cookies: string[] = [];
    const csrf = { 'x-csrf-protection': '1', origin: 'http://localhost:5173' };
    const call = (i: number, method: 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE', url: string, payload?: object) => app.inject({ method, url, headers: { ...csrf, cookie: cookies[i]! }, payload });
    try {
        await c.db.insert(groups).values(groupIds.map((id, i) => ({ id, name: `INTEGRATION-${suffix}-${i}`, faculty: 'Вымышленный факультет', program: 'Учебная программа', year: 1 })));
        await c.db.insert(users).values(ids.map((id, i) => ({ id, email: `integration-${suffix}-${i}@example.test`, fullName: `Вымышленный пользователь ${i}`, faculty: 'Учебный факультет', role: i < 2 ? 'student' : i < 4 ? 'teacher' : 'staff', groupId: i < 2 ? groupIds[i] : null, passwordHash })));
        await c.db.insert(subjects).values({ id: subjectId, name: `Учебная дисциплина ${suffix}` });
        await c.db.insert(teachingAssignments).values(assignmentIds.map((id, i) => ({ id, subjectId, groupId: groupIds[i]!, teacherId: ids[i + 2]!, semester: 1, form: 'Экзамен' })));
        for (let i = 0; i < ids.length; i++) {
            const r = await app.inject({ method: 'POST', url: '/api/auth/login', headers: csrf, payload: { email: `integration-${suffix}-${i}@example.test`, password } });
            assert.equal(r.statusCode, 200, r.body);
            cookies.push(String(r.headers['set-cookie']).split(';')[0]!);
        }
        const save = (i: number, scores: {
            studentId: string;
            score: number | null;
        }[], version = 0) => call(i, 'PUT', `/api/gradebook/${assignmentIds[0]}`, { version, scores });
        assert.equal((await call(0, 'GET', '/api/gradebook/groups')).statusCode, 403);
        const sheets = (await call(2, 'GET', '/api/gradebook/groups')).json().data;
        assert.equal(sheets.length, 1);
        assert.equal(sheets[0].students[0].id, studentA);
        assert.equal((await save(3, [{ studentId: studentA, score: 80 }])).statusCode, 403);
        assert.equal((await save(2, [{ studentId: studentA, score: 80 }, { studentId: studentB, score: 90 }])).statusCode, 403);
        assert.equal((await c.db.select().from(gradeEntries).where(eq(gradeEntries.assignmentId, assignmentIds[0]!))).length, 0, 'no partial batch writes');
        assert.equal((await save(2, [{ studentId: studentA, score: 101 }])).statusCode, 400);
        assert.equal((await save(2, [{ studentId: studentA, score: 80 }, { studentId: studentA, score: 90 }])).statusCode, 400);
        assert.equal((await save(2, [{ studentId: studentA, score: 80 }])).statusCode, 200);
        assert.equal((await save(2, [{ studentId: studentA, score: 90 }])).statusCode, 409);
        assert.equal((await call(0, 'GET', `/api/grades?studentId=${studentB}`)).json().data[0].score, 80);
        assert.equal((await call(1, 'GET', '/api/grades')).json().data[0].score, null);
        const concurrent = await Promise.all([save(2, [{ studentId: studentA, score: 81 }], 1), save(2, [{ studentId: studentA, score: 82 }], 1)]);
        assert.deepEqual(concurrent.map(r => r.statusCode).sort(), [200, 409]);
        await c.db.update(teachingAssignments).set({ deadline: new Date(Date.now() - 1000) }).where(eq(teachingAssignments.id, assignmentIds[0]!));
        assert.equal((await save(2, [{ studentId: studentA, score: 90 }], 2)).statusCode, 409);
        await c.db.update(teachingAssignments).set({ deadline: null }).where(eq(teachingAssignments.id, assignmentIds[0]!));
        assert.equal((await save(2, [{ studentId: studentA, score: null }], 2)).statusCode, 200);
        const contentBase64 = Buffer.from('Вымышленный учебный материал').toString('base64');
        const upload = { assignmentId: assignmentIds[0], title: 'Учебный файл', fileName: 'пример.txt', contentBase64 };
        assert.equal((await call(0, 'POST', '/api/materials', upload)).statusCode, 403);
        assert.equal((await call(3, 'POST', '/api/materials', upload)).statusCode, 403);
        assert.equal((await call(2, 'POST', '/api/materials', { ...upload, fileName: '../secret.txt' })).statusCode, 400);
        assert.equal((await call(2, 'POST', '/api/materials', { ...upload, fileName: 'script.html' })).statusCode, 400);
        const createdFile = await call(2, 'POST', '/api/materials', upload);
        assert.equal(createdFile.statusCode, 201, createdFile.body);
        const fileId = createdFile.json().data.id;
        const list = (await call(0, 'GET', '/api/materials')).json().data;
        assert.equal(list.length, 1);
        assert.equal('contentBase64' in list[0], false);
        assert.deepEqual((await call(1, 'GET', '/api/materials')).json().data, []);
        for (const i of [1, 3, 4])
            assert.equal((await call(i, 'GET', `/api/materials/${fileId}/file`)).statusCode, 403);
        assert.equal((await call(1, 'DELETE', `/api/materials/${fileId}`)).statusCode, 403);
        const download = await call(0, 'GET', `/api/materials/${fileId}/file`);
        assert.equal(download.statusCode, 200);
        assert.equal(download.rawPayload.toString('base64'), contentBase64);
        assert.equal(download.headers['x-content-type-options'], 'nosniff');
        const qbody = { assignmentId: assignmentIds[0], subject: 'Учебный вопрос', text: 'Как выполнить упражнение?' };
        assert.equal((await call(1, 'POST', '/api/inquiries', qbody)).statusCode, 403);
        const inquiry = await call(0, 'POST', '/api/inquiries', qbody);
        assert.equal(inquiry.statusCode, 201);
        const qid = inquiry.json().data.id;
        assert.deepEqual((await call(1, 'GET', '/api/inquiries')).json().data, []);
        assert.deepEqual((await call(3, 'GET', '/api/inquiries')).json().data, []);
        assert.equal((await call(4, 'GET', '/api/inquiries')).statusCode, 403);
        assert.equal((await call(3, 'POST', `/api/inquiries/${qid}/replies`, { text: 'Чужой ответ' })).statusCode, 404);
        assert.equal((await call(0, 'POST', `/api/inquiries/${qid}/replies`, { text: 'Подмена роли' })).statusCode, 403);
        assert.equal((await call(2, 'POST', `/api/inquiries/${qid}/replies`, { text: 'Первый ответ' })).statusCode, 201);
        assert.equal((await call(2, 'POST', `/api/inquiries/${qid}/replies`, { text: 'Второй ответ' })).statusCode, 201);
        assert.equal((await call(0, 'GET', '/api/inquiries')).json().data[0].replies.length, 2);
        assert.equal((await call(2, 'PATCH', `/api/inquiries/${qid}`, { status: 'closed' })).statusCode, 200);
        assert.equal((await call(2, 'POST', `/api/inquiries/${qid}/replies`, { text: 'Закрыто' })).statusCode, 409);
        assert.equal((await call(2, 'PATCH', `/api/inquiries/${qid}`, { status: 'progress' })).statusCode, 200);
        const [foreignNotice] = await c.db.insert(notifications).values({ studentId: studentB, kind: 'news', title: 'Личное уведомление', body: 'Тест' }).returning();
        const ownNotices = (await call(0, 'GET', '/api/notifications')).json().data;
        assert(ownNotices.length > 0);
        assert(ownNotices.every((n: {
            studentId: string;
        }) => n.studentId === studentA));
        assert.equal((await call(0, 'PATCH', `/api/notifications/${foreignNotice.id}/read`)).statusCode, 404);
        assert.equal((await call(0, 'PATCH', '/api/notifications/read-all')).statusCode, 204);
        assert.equal((await call(1, 'GET', '/api/notifications')).json().data[0].readAt, null);
        assert.equal((await call(0, 'PATCH', '/api/user/prefs', { schedule: false })).json().data.schedule, false);
        assert.equal((await call(1, 'GET', '/api/user/prefs')).json().data.schedule, true);
        const lessonBody = { subject: `Учебная дисциплина ${suffix}`, kind: 'lecture', teacherId: teacherA, room: suffix, startsAt: '2031-02-03T09:00:00+03:00', endsAt: '2031-02-03T10:30:00+03:00' };
        const before = (await call(0, 'GET', '/api/notifications')).json().data.length;
        const racingLessons = await Promise.all([call(4, 'POST', `/api/staff/groups/${groupIds[0]}/lessons`, lessonBody), call(4, 'POST', `/api/staff/groups/${groupIds[0]}/lessons`, lessonBody)]);
        assert.deepEqual(racingLessons.map(r => r.statusCode).sort(), [201, 409]);
        assert.equal((await call(0, 'GET', '/api/notifications')).json().data.length, before, 'schedule preference disables generated notifications');
        assert.equal((await call(4, 'POST', `/api/staff/groups/${groupIds[1]}/lessons`, { ...lessonBody, room: 'other-' + suffix.slice(0, 10) })).statusCode, 409, 'teacher collision across groups');
        assert.equal((await call(4, 'POST', `/api/staff/groups/${groupIds[1]}/lessons`, { ...lessonBody, teacherId: teacherB })).statusCode, 409, 'room collision across groups');
        const period = '?from=2031-02-03T00:00:00Z&to=2031-02-04T00:00:00Z';
        assert.equal((await call(0, 'GET', '/api/schedule' + period)).json().data.length, 1);
        assert.equal((await call(1, 'GET', '/api/schedule' + period)).json().data.length, 0);
        assert.equal((await call(2, 'GET', '/api/schedule' + period)).json().data.length, 1);
        assert.equal((await call(3, 'GET', '/api/schedule' + period)).json().data.length, 0);
        const req = await call(0, 'POST', '/api/requests', { type: 'study', purpose: 'Учебный пример', delivery: 'pdf' });
        assert.equal(req.statusCode, 201);
        const rid = req.json().data.id;
        await call(4, 'PATCH', `/api/staff/requests/${rid}/status`, { status: 'in_progress' });
        const draft = await call(4, 'POST', `/api/staff/requests/${rid}/prepare`, { verified: true });
        assert.equal(draft.statusCode, 200);
        const draftId = draft.json().data.draftId;
        assert.equal((await call(4, 'POST', `/api/staff/requests/${rid}/preview`, { draftId })).statusCode, 200);
        const race = await Promise.all([call(0, 'PATCH', `/api/requests/${rid}/cancel`), call(4, 'PATCH', `/api/staff/requests/${rid}/status`, { status: 'ready', draftId })]);
        assert.deepEqual(race.map(r => r.statusCode).sort(), [200, 409]);
        await c.db.delete(sessions).where(eq(sessions.userId, studentA));
        for (const url of ['/api/grades', '/api/inquiries', '/api/notifications', `/api/materials/${fileId}/file`])
            assert.equal((await call(0, 'GET', url)).statusCode, 401);
    }
    finally {
        await app.close();
        const qs = await c.db.select({ id: inquiries.id }).from(inquiries).where(inArray(inquiries.studentId, [studentA, studentB]));
        if (qs.length)
            await c.db.delete(inquiryReplies).where(inArray(inquiryReplies.inquiryId, qs.map(q => q.id)));
        await c.db.delete(inquiries).where(inArray(inquiries.studentId, [studentA, studentB]));
        await c.db.delete(materials).where(inArray(materials.assignmentId, assignmentIds));
        await c.db.delete(gradeEntries).where(inArray(gradeEntries.assignmentId, assignmentIds));
        await c.db.delete(teachingAssignments).where(inArray(teachingAssignments.id, assignmentIds));
        await c.db.delete(requests).where(inArray(requests.studentId, [studentA, studentB]));
        await c.db.delete(lessons).where(inArray(lessons.groupId, groupIds));
        await c.db.delete(notifications).where(inArray(notifications.studentId, ids));
        await c.db.delete(users).where(inArray(users.id, ids));
        await c.db.delete(subjects).where(eq(subjects.id, subjectId));
        await c.db.delete(groups).where(inArray(groups.id, groupIds));
        await c.close();
    }
});
